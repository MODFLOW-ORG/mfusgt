      SUBROUTINE CLNK(ISHAPE1,IFTYPE1,NC1,ISHAPE2,IFTYPE2,NC2,FK)
C--------COMPUTE EFFECTIVE LEAKANCE (CONSTANT TERM) FOR NODE
C--------ISHAPE: 1=CIRCULAR, 2=RECTANGULAR; 3=GENERAL; IFTYPE: TYPE INDEX WITHIN SHAPE
      USE CLN1MODULE, ONLY:  ACLNCOND,NCONDUITYP,ACLNNDS,GRAV,VISK,
     1  IFLINCLN,ACLNREC,NRECTYP
      DOUBLE PRECISION FK,RADFSQ1,RADFSQ2,AR1,AR2,PERI1,PERI2,
     1  EL,CK1,CK2,CK
C--------------------------------------------------------------------------------------
C1 ---GET LOCAL VARIABLES FOR AREA, PERIMETER AND CONDUCTANCE TERM FOR EACH NODE      
      EL = (ACLNNDS(NC1,4) + ACLNNDS(NC2,4)) * 0.5  ! CONNECTION LENGTH IS HALF OF CLN CELL LENGTH
      CALL GETAPK12(ISHAPE1,IFTYPE1,ISHAPE2,IFTYPE2,
     1              AR1,AR2,PERI1,PERI2,CK1,CK2)
      IFLIN = IABS(IFLINCLN(NC1))
C ------------------------------------------------------------------------------------------
      IF(IFLIN.EQ.1)THEN 
C1-------CLN NODE IS LAMINAR FLOW USING HAGEN-POISEUILLE EQUATION          
        IF(VISK.LT.1.0E-10.AND.GRAV.LT.1.0E-10)THEN
C --------THIS PART IS FOR BACKWARD COMPATIBILITY WHERE CONDUITK HAD THE GRAV AND VISCOSITY TERM
          CK1 = CK1 * 4.0 * (AR1/PERI1)**2
          CK2 = CK2 * 4.0 * (AR2/PERI2)**2
        ELSE
          CK1 = 0.5*GRAV/VISK*(AR1/PERI1)**2
          CK2 = 0.5*GRAV/VISK*(AR2/PERI2)**2
        ENDIF  
        CK = 2.0 *CK1*CK2 / (CK1 + CK2)         
        FK = CK / EL  
      ELSEIF(IFLIN.EQ.2) THEN  
C2-------CLN NODE IS TURBULENT FLOW USING DARCY-WEISBACH EQUATION 
        FK = SQRT(32.0*GRAV/EL)       
      ELSEIF(IFLIN.EQ.3) THEN             
C3-------CLN NODE IS TURBULENT FLOW USING HAZEN-WILLIAMS EQUATION
        CK = 2.0 *CK1*CK2 / (CK1 + CK2)
        FK = 0.849 * CK / EL**0.54    
      ELSEIF(IFLIN.EQ.4) THEN  
C4-------CLN NODE IS TURBULENT FLOW USING MANNINGS EQUATION
        CK = 2.0 *CK1*CK2 / (CK1 + CK2)
        FK = 1.0/CK/SQRT(EL)   
      ENDIF  
C7------RETURN
      RETURN
      END
C ------------------------------------------------------------------------------      
      SUBROUTINE GETAPK12(ISHAPE1,IFTYPE1,ISHAPE2,IFTYPE2,
     1                    AR1,AR2,PERI1,PERI2,CK1,CK2)
C     ******************************************************************
C--------RETRIEVE AREA, PERIMETER AND CONDUCTANCE TERM FOR VARIOUS GEOMETRIES
C--------ISHAPE: 1=CIRCULAR, 2=RECTANGULAR, 3=GENERAL; IFTYPE: TYPE INDEX WITHIN SHAPE
C     ******************************************************************      
      USE CLN1MODULE, ONLY: ACLNCOND,NCONDUITYP,ACLNNDS,GRAV,VISK,
     1  IFLINCLN,ACLNREC,NRECTYP,ACLNGENK,ACLNGENA,ACLNGENP,NGENSHPTYP
      DOUBLE PRECISION AR1,AR2,PERI1,PERI2,CK1,CK2      
      
C1A ---FOR NODE 1      
      IF(ISHAPE1.EQ.1)THEN
C1A1---------CLN1 NODE IS A CIRCULAR CONDUIT          
        AR1 = ACLNCOND(IFTYPE1,4) 
        PERI1 = ACLNCOND(IFTYPE1,5)   
        CK1 = ACLNCOND(IFTYPE1,3)
      ELSEIF(ISHAPE1.EQ.2)THEN
C1A2---------CLN1 NODE IS A RECTANGULAR SECTION
        AR1 = ACLNREC(IFTYPE1,5) 
        PERI1 = ACLNREC(IFTYPE1,6)  
        CK1 = ACLNREC(IFTYPE1,4)
      ELSEIF(ISHAPE1.EQ.3)THEN
C1A3---------CLN1 NODE IS A GENERAL SHAPE - USE STORED MAX VALUES
        AR1 = ACLNGENA(IFTYPE1) 
        PERI1 = ACLNGENP(IFTYPE1)  
        CK1 = ACLNGENK(IFTYPE1)
      ENDIF
C1B ---FOR NODE2      
      IF(ISHAPE2.EQ.1)THEN
C1B1---------CLN2 NODE IS A CIRCULAR CONDUIT          
        AR2 = ACLNCOND(IFTYPE2,4) 
        PERI2 = ACLNCOND(IFTYPE2,5)         
        CK2 = ACLNCOND(IFTYPE2,3)
      ELSEIF(ISHAPE2.EQ.2)THEN
C1B2---------CLN2 NODE IS A RECTANGULAR SECTION
        AR2 = ACLNREC(IFTYPE2,5) 
        PERI2 = ACLNREC(IFTYPE2,6)  
        CK2 = ACLNREC(IFTYPE2,4)
      ELSEIF(ISHAPE2.EQ.3)THEN
C1B3---------CLN2 NODE IS A GENERAL SHAPE - USE STORED MAX VALUES
        AR2 = ACLNGENA(IFTYPE2)  
        PERI2 = ACLNGENP(IFTYPE2)  
        CK2 = ACLNGENK(IFTYPE2)
      ENDIF  
C7------RETURN
      RETURN
      END      
C------------------------------------------------------------------------
      SUBROUTINE TURBFUNC(NC1,NC2,IFLIN,HD,TURB)
C     ******************************************************************
C     COMPUTE THE TURBULENT GRADIENT FUNCTION TERM FOR THE VARIOUS FORMULATIONS.
C     ******************************************************************
      USE CLN1MODULE, ONLY:  ACLNCOND,NCONDUITYP,ACLNNDS,GRAV,IFLINCLN,
     1   VISK
      USE GLOBAL, ONLY: HNEW
      DOUBLE PRECISION TURB,FK,RADFSQ,AR,PERI,EL,CONDUITK,HD,ALPHA,BETA,
     1  SQTERM,EPCLIP,PETAM1,PETAM3,PETA,AREPB,APBORE,C1,C2,
     1  AR1,AR2,PERI1,PERI2,CK1,CK2 
      DATA EPCLIP/ 0.01 /      
ccsp      DATA EPCLIP/ 0.1 /      
C-----------------------------------------------------------------------------      
C
C1------RETURN FOR LINEAR FLOW      
      IF(IFLIN.EQ.1) RETURN
C-----------------------------------------------------------------------------  
C2------FOR DARCY-WEISBACH EQUATION
      IF(IFLIN.EQ.2)THEN
C2A-----COMPUTE TERMS ALPHA AND BETA WITHIN THE LOG
        EL = (ACLNNDS(NC1,4)+ACLNNDS(NC2,4)) * 0.5  ! CONNECTION LENGTH IS HALF OF CLN CELL LENGTH SUMS    
        ISHAPE1 = ACLNNDS(NC1,7)
        IFTYPE1 = ACLNNDS(NC1,2)
        ISHAPE2 = ACLNNDS(NC2,7)
        IFTYPE2 = ACLNNDS(NC2,2)
        CALL GETAPK12(ISHAPE1,IFTYPE1,ISHAPE2,IFTYPE2,
     1                AR1,AR2,PERI1,PERI2,CK1,CK2)
        AR = (AR1 + AR2) * 0.5   ! AVERAGE AREA OF CONNECTED CELLS
        PERI = (PERI1 + PERI2) * 0.5 ! AVERAGE PERIMETER OF CONNECTED CELLS
        CONDUITK = (CK1 + CK2) * 0.5 ! AVERAGE ROUGHNESS OF CONNECTED CELLS
        ALPHA = CONDUITK * PERI / (14.84 * AR)
        SQTERM = (AR/PERI)**3 * GRAV / EL
        BETA = 0.222 * VISK / SQRT(SQTERM)          
        IF(HD.GT.EPCLIP)THEN
          TURB = HD**(-0.5) * LOG10 (ALPHA + BETA/SQRT(HD))
        ELSE
C2B-------FLATTEN AND SMOOTH THE FUNCTION BEFORE IT GROWS VERY LARGE  
          AREPB = ALPHA * SQRT(EPCLIP) + BETA
          APBORE = ALPHA + BETA/SQRT(EPCLIP)
          C1 = -AREPB * LOG(APBORE) - BETA
          C1 = C1 / (9.21034 * EPCLIP**2.5 * AREPB)
          C2 = LOG10(APBORE)/SQRT(EPCLIP) - C1*EPCLIP**2
          TURB = C1*HD**2 + C2
        ENDIF
C-------------------------------------------------------------------------------        
      ELSEIF(IFLIN.EQ.3.OR.IFLIN.EQ.4)THEN    
C3------FOR POWER-OF-HD STYLE EQUATIONS
C-------------------------------------------------------------------------------          
        IF(IFLIN.EQ.3)THEN 
C3A------FOR HAZEN-WILLIAMS EQUATION            
          PETA = 0.54 
        ELSEIF(IFLIN.EQ.4)THEN    
C3B------FOR MANNINGS EQUATION
          PETA = 0.5
        ENDIF
C--------------------------------------------------------------------
        PETAM1 = PETA-1.0
        IF(HD.GT.EPCLIP)THEN
          TURB = HD**PETAM1
        ELSE
C3C-------FLATTEN AND SMOOTH THE FUNCTION BEFORE IT GROWS VERY LARGE
         PETAM3 = PETA - 3.0   
         TURB= 0.5*(PETAM1*EPCLIP**PETAM3*HD**2 - EPCLIP**PETAM1*PETAM3)
C3C-------straighten FUNCTION BEFORE IT GROWS VERY LARGE
csp         PETAM2 = PETA - 2.0   
csp         TURB= PETAM1 * EPCLIP**PETAM2 * HD - PETAM2 * EPCLIP**PETAM1 
        ENDIF
      ENDIF
      TURB = ABS(TURB)
C
C4-----RETURN.
      RETURN
      END
C--------------------------------------------------------------------------------------
      SUBROUTINE CLNR(ISHAPE,IFTYPE,FRAD)
C--------COMPUTE RADIUS FOR CONNECTION OF CLN SEGMENT TO 3-D GRID WITH THEIM EQUATION
C--------ISHAPE: 1=CIRCULAR, 2=RECTANGULAR, 3=GENERAL; IFTYPE: TYPE INDEX WITHIN SHAPE
      USE CLN1MODULE, ONLY: ACLNCOND,NCONDUITYP,ACLNREC,NRECTYP,
     1  ACLNGENA,ACLNGENP,NGENSHPTYP
      DOUBLE PRECISION FRAD,AREAMAX,PERIMAX
C--------------------------------------------------------------------------------------
      IF(ISHAPE.EQ.1)THEN
C1-------CLN NODE IS A CIRCULAR CONDUIT
        FRAD = ACLNCOND(IFTYPE,2)
      ELSEIF(ISHAPE.EQ.2)THEN
C2-------CLN NODE IS A RECTANGULAR SECTION: FRAD IS HALF OF HYDRAULIC RADIUS
        FRAD = 0.5 * ACLNREC(IFTYPE,4)/ACLNREC(IFTYPE,5)
      ELSEIF(ISHAPE.EQ.3)THEN
C3-------CLN NODE IS A GENERAL SHAPE: FRAD IS HYDRAULIC RADIUS AT MAX DEPTH 
C3-------FOR VERTICAL FLOW, A GENERAL SECTION DOES NOT MAKE SENSE (BUT LEAVE THIS SECTION HERE FOR NOW)
        AREAMAX = ACLNGENA(IFTYPE)
        PERIMAX = ACLNGENP(IFTYPE)
        IF(PERIMAX.GT.0.0) THEN
          FRAD = AREAMAX / PERIMAX
        ELSE
          FRAD = 0.0
        ENDIF
      ENDIF
C7------RETURN
      RETURN
      END
C--------------------------------------------------------------------------------------
      SUBROUTINE CLNP(ISHAPE,IFTYPE,FPER)
C--------COMPUTE EFFECTIVE PERIMETER FOR CONNECTION OF CLN SEGMENT TO 3-D GRID
C--------ISHAPE: 1=CIRCULAR, 2=RECTANGULAR, 3=GENERAL; IFTYPE: TYPE INDEX WITHIN SHAPE
      USE CLN1MODULE, ONLY: ACLNCOND,NCONDUITYP,ACLNREC,NRECTYP,
     1  ACLNGENP,NGENSHPTYP
      DOUBLE PRECISION FPER
C--------------------------------------------------------------------------------------
      PI = 3.1415926
      IF(ISHAPE.EQ.1)THEN
C1-------CLN NODE IS A CIRCULAR CONDUIT
        FPER = 2 * PI * ACLNCOND(IFTYPE,2)
      ELSEIF(ISHAPE.EQ.2)THEN
C2-------CLN NODE IS A RECTANGULAR SECTION
        FPER = 2 * (ACLNREC(IFTYPE,2) + ACLNREC(IFTYPE,3))
      ELSEIF(ISHAPE.EQ.3)THEN
C3-------CLN NODE IS A GENERAL SHAPE - RETURN STORED MAXIMUM PERIMETER
        FPER = ACLNGENP(IFTYPE)
      ENDIF
C7------RETURN
      RETURN
      END
C--------------------------------------------------------------------------------
      SUBROUTINE CLNPGET(ISHAPE,IFTYPE,FPER)
C--------GET EFFECTIVE TOTAL PERIMETER FOR CONNECTION OF CLN SEGMENT TO 3-D GRID FROM ARRAYS
C--------ISHAPE: 1=CIRCULAR, 2=RECTANGULAR, 3=GENERAL; IFTYPE: TYPE INDEX WITHIN SHAPE
      USE CLN1MODULE, ONLY: ACLNCOND,NCONDUITYP,ACLNREC,NRECTYP,
     1  ACLNGENP,NGENSHPTYP
      DOUBLE PRECISION FPER
C--------------------------------------------------------------------------------------
      IF(ISHAPE.EQ.1)THEN
C1-------CLN NODE IS A CIRCULAR CONDUIT
        FPER = ACLNCOND(IFTYPE,5)
      ELSEIF(ISHAPE.EQ.2)THEN
C2-------CLN NODE IS A RECTANGULAR SECTION
        FPER = ACLNREC(IFTYPE,6) 
      ELSEIF(ISHAPE.EQ.3)THEN
C3-------CLN NODE IS A GENERAL SHAPE - RETURN STORED MAXIMUM PERIMETER
        FPER = ACLNGENP(IFTYPE)
      ENDIF
C7------RETURN
      RETURN
      END 
C-------------------------------------------------------------------------------
      SUBROUTINE CLNPW(ICLN,HD,PERIW,IGWCLN)
C--------COMPUTE WETTED X-SECTIONAL PERIMETER FOR HORIZONTAL CLN CELL
      USE CLN1MODULE, ONLY:  ACLNCOND,NCONDUITYP,ACLNNDS,ACLNREC,NRECTYP
      USE GLOBAL, ONLY: NODES,HNEW
      DOUBLE PRECISION PERIW,RADFSQ,HD,FRAD,BBOT,DEPTH,
     1  AFAC,BFAC,CFAC,DTOP,EFAC
      DOUBLE PRECISION CLNGEN_INTERP  
      INTEGER IGWCLN ! INDEX OF CONNECTION = 0 FOR CLN-CLN; =1 FOR GW-CLN
C--------------------------------------------------------------------------------------
      N = ACLNNDS(ICLN,1)
      ISHAPE = ACLNNDS(ICLN,7)
      IFTYPE = ACLNNDS(ICLN,2)
      BBOT = ACLNNDS(ICLN,5)
      DEPTH = HD - BBOT      
      IF(ISHAPE.EQ.1)THEN
C1-------CLN NODE IS A CIRCULAR CONDUIT
        PI = 3.1415926
        FRAD = ACLNCOND(IFTYPE,2)
        IF(DEPTH.LE.0)THEN
          PERIW = 0.0
        ELSEIF(DEPTH.LE.FRAD)THEN
          PERIW = 2.0*FRAD*ACOS((FRAD-DEPTH)/FRAD)
        ELSEIF(DEPTH.LE.2.0*FRAD)THEN
          PERIW = 2.0*FRAD*(PI - ACOS((DEPTH-FRAD)/FRAD))
        ELSE
          PERIW = 2* PI *FRAD
        ENDIF
      ELSEIF(ISHAPE.EQ.2)THEN
C2-------CLN NODE IS A RECTANGULAR SECTION
        HEIGHT = ACLNREC(IFTYPE,3)
        WIDTH = ACLNREC(IFTYPE,2)
        EPSILON = 0.01 
        IF(DEPTH.LE.0.0) DEPTH = 0.0
        IF(DEPTH.LT.HEIGHT)THEN
          PERIW = ACLNREC(IFTYPE,2) + 2.0* DEPTH
cc          PERIW = ACLNREC(IFTYPE,2)   ! Wide rectangle assumption
        ELSEIF(DEPTH.LT.(HEIGHT + EPSILON))THEN 
          DTOP = DEPTH - HEIGHT
          EFAC = WIDTH + 2*HEIGHT
          CFAC = 2.0
          BFAC = (3*WIDTH - 4 * EPSILON) / EPSILON**2
          AFAC = -(2.0*BFAC*EPSILON + 2.0) / (3 * EPSILON**2)
          PERIW = AFAC*DTOP**3 + BFAC*DTOP**2 + CFAC*DTOP + EFAC
        ELSE    
          PERIW = ACLNREC(IFTYPE,2) + 2.0 * HEIGHT   + WIDTH  
        ENDIF   
C ------FOR GW-CLN CONNECTION, NEED TO SMOOTHEN RECTANGLE TO ZERO WHEN DEPTH COMES TO ZERO
        IF(IGWCLN.EQ.1)THEN
C5----------PROVIDE SMOOTH PATCHING FUNCTION WHEN DEPTH DROPS TO ZERO
          EPSILON = 0.01
          FPATCH = 1.0D0
          HR = DEPTH
          IF(HR.LT.EPSILON)THEN
            FPATCH = 2.0D0*(HR/EPSILON)**3 + 3.0D0*(HR/EPSILON)**2 
            PERIW = PERIW * FPATCH 
          ENDIF            
        ENDIF
      ELSEIF(ISHAPE.EQ.3)THEN
C3-------CLN NODE IS A GENERAL SHAPE - INTERPOLATE FROM TABLE
        IF(DEPTH.LE.0.0) THEN
          PERIW = 0.0
        ELSE
          PERIW = CLNGEN_INTERP(DEPTH,3,IFTYPE) 
        ENDIF
      ENDIF
C
C5------RETURN.
      RETURN
      END
C-------------------------------------------------------------------------------
      SUBROUTINE CLNAW(ICLN,HD,AREAW)
C--------COMPUTE WETTED X-SECTIONAL FLOW AREA FOR NODE
      USE CLN1MODULE, ONLY:  ACLNCOND,NCONDUITYP,ACLNNDS,ACLNREC,NRECTYP
      USE GLOBAL, ONLY: NODES,HNEW
      DOUBLE PRECISION AREAW,RADFSQ,HD,FRAD,BBOT,DEPTH
      DOUBLE PRECISION CLNGEN_INTERP
C--------------------------------------------------------------------------------------
      N = ACLNNDS(ICLN,1)
      ISHAPE = ACLNNDS(ICLN,7)
      IFTYPE = ACLNNDS(ICLN,2)
      BBOT = ACLNNDS(ICLN,5)
      DEPTH = HD - BBOT
      IF(ISHAPE.EQ.1)THEN
C1-------CLN NODE IS A CIRCULAR CONDUIT
        PI = 3.1415926
        FRAD = ACLNCOND(IFTYPE,2)
        IF(DEPTH.LE.0)THEN
          AREAW = 0.0
        ELSEIF(DEPTH.LE.FRAD)THEN
          AREAW = FRAD*FRAD*ACOS((FRAD-DEPTH)/FRAD) - (FRAD-DEPTH)*
     1         SQRT(FRAD*FRAD - (FRAD-DEPTH)**2)
        ELSEIF(DEPTH.LE.2.0*FRAD)THEN
          AREAW = FRAD*FRAD*(PI - ACOS((DEPTH-FRAD)/FRAD))
     1    - (FRAD-DEPTH) * SQRT(FRAD*FRAD - (FRAD-DEPTH)**2)
        ELSE
          AREAW = PI *FRAD*FRAD
        ENDIF
      ELSEIF(ISHAPE.EQ.2)THEN
C2-------CLN NODE IS A RECTANGULAR SECTION
        HEIGHT = ACLNREC(IFTYPE,3)
        IF(DEPTH.LE.0)THEN
          AREAW = 0.0  
        ELSEIF(DEPTH.LT.HEIGHT)THEN
          AREAW = ACLNREC(IFTYPE,2) * DEPTH
        ELSE
          AREAW = ACLNREC(IFTYPE,2) * HEIGHT   
        ENDIF 
      ELSEIF(ISHAPE.EQ.3)THEN
C3-------CLN NODE IS A GENERAL SHAPE - INTERPOLATE FROM TABLE
        IF(DEPTH.LE.0.0) THEN
          AREAW = 0.0
        ELSE
          AREAW = CLNGEN_INTERP(DEPTH,2,IFTYPE)
        ENDIF
      ENDIF
C
C5------RETURN.
      RETURN
      END
C-----------------------------------------------------------------------
      DOUBLE PRECISION FUNCTION CLNGEN_INTERP(DEPTH,IPROP,IFTYPE)
C     ******************************************************************
C     INTERPOLATE PROPERTY VALUE FROM GENERAL SHAPE TABLE
C     IPROP: 2=AREA, 3=WETTED PERIMETER, 4=TOP WIDTH
C     ******************************************************************
C
C        SPECIFICATIONS:
C     ------------------------------------------------------------------
      USE CLN1MODULE, ONLY: ACLNGEN,NGENTABROWS
      DOUBLE PRECISION DEPTH,HVAL,A,B,HROW,FROW,HROWM1,FROWM1
C     ------------------------------------------------------------------
C1------SET AT FIRST ROW VALUE IF DEPTH IS LESS THAN FIRST TABLE DEPTH
      HVAL = ACLNGEN(1,1,IFTYPE)
      IF(DEPTH.LE.HVAL) THEN 
        CLNGEN_INTERP = ACLNGEN(IPROP,1,IFTYPE) 
        RETURN
      ENDIF    
C2------SET AT LAST ROW VALUE IF DEPTH IS GREATER THAN LAST TABLE DEPTH
      HVAL = ACLNGEN(1,NGENTABROWS,IFTYPE)
      IF(DEPTH.GE.HVAL) THEN 
        CLNGEN_INTERP = ACLNGEN(IPROP,NGENTABROWS,IFTYPE) 
        RETURN
      ENDIF          
C3------FIND LOCATION IN TABLE AND INTERPOLATE FOR ANYTHING IN BETWEEN
      DO IROW = 2,NGENTABROWS
        HROW = ACLNGEN(1,IROW,IFTYPE)
        IF(DEPTH.LE.HROW) THEN
          HROWM1 = ACLNGEN(1,IROW-1,IFTYPE)
          FROW = ACLNGEN(IPROP,IROW,IFTYPE)
          FROWM1 = ACLNGEN(IPROP,IROW-1,IFTYPE)
          A = FROW - FROWM1
          B = HROW - HROWM1
          CLNGEN_INTERP = FROWM1 + A / B * (DEPTH - HROWM1)
          RETURN
        ENDIF        
      ENDDO    
C4------FALLBACK TO LAST VALUE (SHOULD NOT REACH HERE)
      CLNGEN_INTERP = ACLNGEN(IPROP,NGENTABROWS,IFTYPE)
      RETURN
      END FUNCTION CLNGEN_INTERP
