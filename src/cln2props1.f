      SUBROUTINE SCLN2GEN1RP
C     ******************************************************************
C      ALLOCATE SPACE AND READ PROPERTIES FOR GENERAL SHAPE TYPE CLNs
C      TABULAR INPUT: DEPTH VS AREA, WETTED PERIMETER, TOP WIDTH
C     ******************************************************************
C
C        SPECIFICATIONS:
C     ------------------------------------------------------------------
      USE CLN1MODULE
      USE GLOBAL, ONLY: IUNIT,IOUT,NEQS,NODES,NROW,NCOL,IFREFM,IUNSTR,
     *                  INCLN
      DOUBLE PRECISION AREAF,PERIF
      CHARACTER*400 LINE
C----------------------------------------------------------------------------------------
C------ALLOCATE SPACE FOR GENERAL SHAPE CLNs
C------ACLNGEN(4, NGENTABROWS, NGENSHPTYP): (1)DEPTH, (2)AREA, (3)WETPERI, (4)TOPWID
C------ACLNGENK: CONDUITK, ACLNGENA: MAX AREA, ACLNGENP: MAX PERIMETER
      ALLOCATE (ACLNGEN(4,NGENTABROWS,NGENSHPTYP))
      ALLOCATE (ACLNGENK(NGENSHPTYP))
      ALLOCATE (ACLNGENA(NGENSHPTYP))
      ALLOCATE (ACLNGENP(NGENSHPTYP))
      WRITE(IOUT,23)
23    FORMAT(/20X,' GENERAL CLN SECTION INFORMATION'/
     1  20X,40('-')/5X,'FOR EACH TYPE: CONDUITK FOLLOWED BY TABLE OF ',
     2  'DEPTH, AREA, WETTED PERIMETER, TOP WIDTH')
C------READ GENERAL SHAPE PROPERTIES FOR EACH TYPE
      DO IT=1,NGENSHPTYP
C------READ CONDUITK FOR THIS TYPE
        CALL URDCOM(INCLN,IOUT,LINE)
        IF(IFREFM.EQ.0) THEN
          READ(LINE,'(I10,F10.3)') IFNO,CONDUITK
        ELSE
          LLOC=1
          CALL URWORD(LINE,LLOC,ISTART,ISTOP,2,IFNO,R,IOUT,INCLN)
          CALL URWORD(LINE,LLOC,ISTART,ISTOP,3,I,CONDUITK,IOUT,INCLN)
        END IF
        ACLNGENK(IT) = CONDUITK
        WRITE(IOUT,24) IFNO,CONDUITK
24      FORMAT(/5X,'GENERAL TYPE ',I5,' CONDUITK = ',E15.6)
        WRITE(IOUT,25)
25      FORMAT(5X,'DEPTH',12X,'AREA',8X,'WETTED PERI',6X,'TOP WIDTH'/
     1         5X,5('-'),12X,4('-'),8X,11('-'),6X,9('-'))
C------READ TABLE ROWS: DEPTH, AREA, WETTED PERIMETER, TOP WIDTH
        DO IR=1,NGENTABROWS
          CALL URDCOM(INCLN,IOUT,LINE)
          IF(IFREFM.EQ.0) THEN
            READ(LINE,'(4F10.3)') FDEPTH,FAREA,FWETPERI,FTOPWID
          ELSE
            LLOC=1
            CALL URWORD(LINE,LLOC,ISTART,ISTOP,3,I,FDEPTH,IOUT,INCLN)
            CALL URWORD(LINE,LLOC,ISTART,ISTOP,3,I,FAREA,IOUT,INCLN)
            CALL URWORD(LINE,LLOC,ISTART,ISTOP,3,I,FWETPERI,IOUT,INCLN)
            CALL URWORD(LINE,LLOC,ISTART,ISTOP,3,I,FTOPWID,IOUT,INCLN)
          END IF
          ACLNGEN(1,IR,IT) = FDEPTH
          ACLNGEN(2,IR,IT) = FAREA
          ACLNGEN(3,IR,IT) = FWETPERI
          ACLNGEN(4,IR,IT) = FTOPWID
          WRITE(IOUT,26) FDEPTH,FAREA,FWETPERI,FTOPWID
26        FORMAT(5X,4(1X,E15.6))
        ENDDO
C------STORE MAX AREA AND PERIMETER FROM LAST TABLE ROW (FULL DEPTH VALUES)
        AREAF = ACLNGEN(2,NGENTABROWS,IT)
        PERIF = ACLNGEN(3,NGENTABROWS,IT)
        ACLNGENA(IT) = AREAF
        ACLNGENP(IT) = PERIF
        WRITE(IOUT,27) AREAF,PERIF
27      FORMAT(5X,'MAX AREA = ',E15.6,' MAX PERIMETER = ',E15.6)
      ENDDO
C--------RETURN
      RETURN
      END
