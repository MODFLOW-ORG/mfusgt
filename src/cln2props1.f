      SUBROUTINE CLNA(ISHAPE,IFTYPE,AREAF)
C--------COMPUTE X-SECTIONAL FLOW AREA FOR NODE (MAXIMUM/FULL AREA)
C--------ISHAPE: 1=CIRCULAR, 2=RECTANGULAR, 3=GENERAL; IFTYPE: TYPE INDEX WITHIN SHAPE
      USE CLN1MODULE, ONLY: ACLNCOND,NCONDUITYP,ACLNREC,NRECTYP,
     1  ACLNGENA,NGENSHPTYP
      DOUBLE PRECISION AREAF,RADFSQ
C--------------------------------------------------------------------------------------
      PI = 3.1415926
      IF(ISHAPE.EQ.1)THEN
C1-------CLN NODE IS A CIRCULAR CONDUIT
        RADFSQ = ACLNCOND(IFTYPE,2)**2
        AREAF = PI * RADFSQ
      ELSEIF(ISHAPE.EQ.2)THEN
C2-------CLN NODE IS A RECTANGULAR SECTION
        AREAF = ACLNREC(IFTYPE,2) * ACLNREC(IFTYPE,3)
      ELSEIF(ISHAPE.EQ.3)THEN
C3-------CLN NODE IS A GENERAL SHAPE - RETURN STORED MAXIMUM AREA
        AREAF = ACLNGENA(IFTYPE)
      ENDIF
C7------RETURN
      RETURN
      END
