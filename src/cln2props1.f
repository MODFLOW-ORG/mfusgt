C--------GET X-SECTIONAL FLOW AREA FOR NODE FROM RESPECTIVE ARRAY (MAXIMUM/FULL AREA)
C--------ISHAPE: 1=CIRCULAR, 2=RECTANGULAR, 3=GENERAL; IFTYPE: TYPE INDEX WITHIN SHAPE
      USE CLN1MODULE, ONLY: ACLNCOND,NCONDUITYP,ACLNREC,NRECTYP,
     1  ACLNGENA,NGENSHPTYP
